"""Command-line entry point for pytest-mcp-plugin.

Provides:
  - `mcp-test init`     scaffold a tests/ directory
  - `mcp-test run`      run the pytest suite against an MCP server
  - `mcp-test demo`     run the bundled demo server + example tests (zero setup)
  - `mcp-test snapshot` snapshot helpers
  - `mcp-test coverage` print a coverage report for an MCP server
  - `mcp-test validate` validate tool schemas
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import click

__version__ = "0.2.3"


