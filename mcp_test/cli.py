@click.group()
@click.version_option(version=__version__, prog_name="mcp-test")
def main() -> None:
    """pytest for MCP servers."""


@main.command()
@click.option("--dir", "test_dir", default="tests", help="Test directory name (default: tests)")
def init(test_dir: str) -> None:
    """Scaffold a tests/ directory with example MCP tests."""
    test_path = Path(test_dir)

    if test_path.exists() and any(test_path.iterdir()):
        click.echo(f"⚠️  Directory '{test_dir}' already exists and is not empty.")
        if not click.confirm("Overwrite?"):
            raise SystemExit(0)

    test_path.mkdir(parents=True, exist_ok=True)

    test_file = test_path / "test_server.py"
    test_file.write_text(EXAMPLE_TEST)
    click.echo(f"✅ Created {test_file}")

    conftest_file = test_path / "conftest.py"
    conftest_file.write_text(CONFTEST)
    click.echo(f"✅ Created {conftest_file}")

    click.echo()
    click.echo("Run your tests with:")
    click.echo(f'  pytest {test_dir} --mcp-command "python your_server.py"')


@main.command()
@click.option(
    "--command",
    "-c",
    default=None,
    help="MCP server command (auto-discovered from pyproject.toml if not set)",
)
@click.option("--timeout", "-t", default=None, type=float, help="Request timeout (seconds)")
@click.option(
    "--timeout-method",
    "timeout_methods",
    multiple=True,
    metavar="METHOD=SECONDS",
    help="Per-method timeout override passed through to pytest",
)
@click.option("--smart-timeouts", is_flag=True, help="Enable built-in method-family timeouts")
@click.option("--trace", default=None, help="Write MCP wire trace JSONL to this path")
@click.option("--verbose", "-v", is_flag=True, help="Verbose output")
@click.option("--watch", "-w", is_flag=True, help="Re-run tests on file changes")
@click.argument("pytest_args", nargs=-1, type=click.UNPROCESSED)
def run(
    command: str | None,
    timeout: float | None,
    timeout_methods: tuple[str, ...],
    smart_timeouts: bool,
    trace: str | None,
    verbose: bool,
    watch: bool,
    pytest_args: tuple,
) -> None:
    """Run pytest against an MCP server."""
    from .runner import discover_command, discover_timeout, _run_watch_mode

    if command is None:
        command = discover_command()
        if command is None:
            click.echo(
                "❌ No --command provided and no [tool.mcp-test] command in pyproject.toml"
            )
            raise SystemExit(1)
        click.echo(f"🔍 Auto-discovered command: {command}")

    if timeout is None:
        timeout = discover_timeout()

    args = [
        sys.executable,
        "-m",
        "pytest",
        f"--mcp-command={command}",
        f"--mcp-timeout={timeout}",
    ]
    for timeout_method in timeout_methods:
        args.append(f"--mcp-timeout-method={timeout_method}")
    if smart_timeouts:
        args.append("--mcp-smart-timeouts")
    if trace:
        args.append(f"--mcp-trace={trace}")
    if verbose:
        args.append("-v")
    args.extend(pytest_args)

    if watch:
        raise SystemExit(_run_watch_mode(args))

    result = subprocess.run(args, cwd=os.getcwd())
    raise SystemExit(result.returncode)


@main.command()
@click.option(
    "--keep",
    is_flag=True,
    help="Keep the generated demo directory after running (default: clean up)",
)
@click.option("--verbose", "-v", is_flag=True, help="Verbose pytest output")
def demo(keep: bool, verbose: bool) -> None:
    """Run the bundled demo server + example tests in 5 seconds.

    No setup required. Spawns python -m mcp_test._demo_server, runs a small
    pytest suite against it, and prints the result.
    """
    server_cmd = f"{sys.executable} -m mcp_test._demo_server"
    workdir = Path(tempfile.mkdtemp(prefix="mcptest-demo-"))
    test_file = workdir / "test_demo.py"
    test_file.write_text(DEMO_TEST)

    click.echo("🚀 mcp-test demo")
    click.echo(f"   server  : {server_cmd}")
    click.echo(f"   workdir : {workdir}")
    click.echo()

    args = [
        sys.executable,
        "-m",
        "pytest",
        str(test_file),
        f"--mcp-command={server_cmd}",
        "--mcp-timeout=10",
    ]
    if verbose:
        args.append("-v")
    else:
        args.append("--tb=short")

    try:
        result = subprocess.run(args)
    finally:
        if not keep:
            shutil.rmtree(workdir, ignore_errors=True)
        else:
            click.echo()
            click.echo(f"📂 Demo files kept at: {workdir}")

    if result.returncode == 0:
        click.echo()
        click.echo("✅ Demo passed. Now write tests for your own MCP server:")
        click.echo("   mcp-test init")
    raise SystemExit(result.returncode)


